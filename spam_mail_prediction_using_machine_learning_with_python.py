import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

"""Data collection and preprocessing"""

raw_mail_data = pd.read_csv('mail_data.csv')

print(raw_mail_data)

#Replace the null value with null string
mail_data = raw_mail_data.where((pd.notnull(raw_mail_data)),'')

# printing the first 5 rows from the dataframe
mail_data.head()

#Checking the number of rows and columns in the dataframe
mail_data.shape

"""Label encoding"""

#Label spam mail is 0; and ham mail is 1;

mail_data.loc[mail_data['Category'] == 'spam', 'Category',] = 0
mail_data.loc[mail_data['Category'] == 'ham', 'Category',] = 1

#seperating the data as text and label

X = mail_data['Message']

Y = mail_data['Category']

print(X)

print(Y)

"""Splitting the training data and testing data"""

X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size=0.2, random_state=3)

print(X_train.shape)
print(X_test.shape)
print(Y_train.shape)
print(Y_test.shape)

print(type(X_train))

#converting the text data to numerical values

feature_extraction = TfidfVectorizer(min_df = 1, stop_words='english', lowercase=True)

X_train_features = feature_extraction.fit_transform(X_train)
X_test_features = feature_extraction.transform(X_test)

#convert y train and y test as integers

Y_train = Y_train.astype('int')
Y_test = Y_test.astype('int')

print(X_train)
print(X_train_features)
print(Y_train)

"""Training the Logistic regression"""

model = LogisticRegression()

#Training the Logistic regression with the training data

model.fit(X_train_features, Y_train)

"""Evualating the trained model"""

#predict on training data

prediction_on_training_data = model.predict(X_train_features)
accuracy_on_training_data = accuracy_score(Y_train, prediction_on_training_data)

accuracy_on_training_data

#predict on test data

prediction_on_test_data = model.predict(X_test_features)
accuracy_on_test_data = accuracy_score(Y_test, prediction_on_test_data)

accuracy_on_test_data

"""Building preditive system"""

input_mail = ["I've been searching for the right words to thank you for this breather. I promise i wont take your help for granted and will fulfil my promise. You have been wonderful and a blessing at all times."]

#Convert text to feature vectors

input_data_features = feature_extraction.transform(input_mail)

#making prediction

prediction = model.predict(input_data_features)
print(prediction)

if(prediction[0]==1):
    print('Ham mail')
else:
    print('Spam mail')